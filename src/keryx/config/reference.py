"""`docs/configuration.md`, generated from `Settings` so it cannot drift from it.

    uv run python -m keryx.config.reference > docs/configuration.md

`tests/test_docs_sync.py` fails when the file on disk is not what this renders.
"""

from pathlib import Path
from typing import Any

from keryx.config.files import XDG_HOMES
from keryx.config.permissions import PROTECTED_KEYS
from keryx.config.settings import (
    GROUPS,
    SCREEN_OF_GROUP,
    SCREENS,
    TAB_OF_GROUP,
    TABS,
    Settings,
    env_var_name,
    field_advanced,
    field_group,
    field_title,
    is_secret,
)

#: Defaults that depend on the machine, written as what they are derived from, so the
#: generated file is the same on every machine that renders it.
SYMBOLIC_DEFAULTS = {
    f"{kind}_dir": f"`${XDG_HOMES[kind][0]}/keryx` (`{XDG_HOMES[kind][1]}/keryx`)"
    for kind in ("data", "state", "cache")
} | {"skills_dir": "`$CLAUDE_CONFIG_DIR/skills` (`~/.claude/skills`)"}

#: Each entry's key, then its title: the name the Mac app shows in place of the key, and
#: where on its tab the app shows it.
HEADER = "| Setting | Title | In the app | Default | Service may change | What it is |"

INTRO = """\
# Configuration

<!-- Generated by `uv run python -m keryx.config.reference`; do not edit by hand. -->

Every setting Keryx reads, by the name you set it under, and by its title: what the Mac app
calls it. The usual way to set them is `uv run keryx setup` (a wizard that asks only for
what is missing) or `uv run keryx config set KEY VALUE`; `uv run keryx config list` shows
each one with where its value came from.

**Where they live.** `KERYX_HOME` (default `$XDG_CONFIG_HOME/keryx`, which is
`~/.config/keryx`, on Linux and macOS alike) holds `config.toml` for the plain settings and
`secrets.toml` for the credentials, both readable by you alone. A secret is never put on a
command line: `keryx config set KEY --stdin` reads it from standard input, and
`--from-env VAR` from a variable. The PIN is not in either file: it lives beside them in
`KERYX_HOME/pin`, written once (see `SECURITY.md`). Keep that directory out of a
dotfiles repository. What Keryx keeps is in `DATA_DIR`, `STATE_DIR` and `CACHE_DIR`, the
XDG data, state and cache directories below.

**Which value wins**, first to last: the process environment (a systemd `Environment=`,
say), `secrets.toml`, `config.toml`, and the default below. Nothing is read from the
working directory: an install that still has a `.env` there, or its files in `~/.jarvis`,
moves them with `keryx migrate`, and `keryx serve` refuses to start until it has.

**What the running service may change.** Keryx can change some of its own settings — the
voice model's `set_config` tool, or a subagent running `keryx config set` in a task — and
only those marked *yes* below, until you say otherwise with `keryx config unlock KEY` or
`keryx config lock KEY`. The ones marked *never* are protected: every credential, and
every setting that is a line of defence (who may call, the approval allowlist, filing
issues in public, spending caps, deletion, the network, the debug switches). Nothing unlocks them.

**In the Mac app** most settings are on the Configuration screen's {count} tabs, and each
section below names its own:
{tabs}.
The voice's models and this machine's model servers are on screens of their own instead:
{screens}.
Each is the one place its settings are changed, and Configuration's search still finds
them and takes you there.
A tab opens on its *key* settings — what you set to get a first call working, or change
from time to time, how long your calls and tasks are kept and how many tasks a day may
run included — and keeps the rest under an *Advanced* disclosure: tuning and internals,
such as turn-detection numbers, server addresses, ports, timeouts, per-task caps, folders,
unit names, the log level and the debug switches.
"""


#: How many tabs there are, as the intro says it.
_NUMBERS = {5: "five", 6: "six", 7: "seven", 8: "eight", 9: "nine", 10: "ten"}


def _default(value: Any) -> str:
    if value is None or value == [] or value == {}:
        return ""
    if isinstance(value, bool):
        return f"`{str(value).lower()}`"
    if isinstance(value, list):
        return f"`{','.join(map(str, value))}`"
    if isinstance(value, float) and value.is_integer():
        return f"`{int(value)}`"
    return f"`{value}`"


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render() -> str:
    """The whole of `docs/configuration.md`."""
    tabs = ", ".join(tab.title for tab in TABS.values())
    screens = " and ".join(f"the {title} screen" for title in SCREENS.values())
    lines = [INTRO.format(count=_NUMBERS[len(TABS)], tabs=tabs, screens=screens)]
    for group, title in GROUPS.items():
        names = [name for name in Settings.model_fields if field_group(name) == group]
        if group in SCREEN_OF_GROUP:
            place = f"the {SCREENS[SCREEN_OF_GROUP[group]]} screen"
        else:
            place = f"the {TABS[TAB_OF_GROUP[group]].title} tab"
        lines += [
            f"## {title}", "", f"In the Mac app: {place}.", "",
            HEADER, "|---|---|---|---|---|---|",
        ]
        for name in names:
            info = Settings.model_fields[name]
            key = env_var_name(name)
            if name in SYMBOLIC_DEFAULTS:
                default = SYMBOLIC_DEFAULTS[name]
            elif info.is_required():
                default = "*required*"
            else:
                default = _default(info.get_default(call_default_factory=True))
            if is_secret(name):
                default = f"{default} (secret)".strip()
            extra = info.json_schema_extra if isinstance(info.json_schema_extra, dict) else {}
            writable = "never" if key in PROTECTED_KEYS else (
                "yes" if extra.get("service_writable") else "no"
            )
            shown = "advanced" if field_advanced(name) else "key"
            lines.append(
                f"| `{key}` | {_cell(field_title(name))} | {shown} | {_cell(default)} | "
                f"{writable} | "
                f"{_cell(info.description or '')} |"
            )
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def write(path: Path) -> None:  # pragma: no cover - the command line below
    path.write_text(render(), encoding="utf-8")


if __name__ == "__main__":  # pragma: no cover
    print(render(), end="")
